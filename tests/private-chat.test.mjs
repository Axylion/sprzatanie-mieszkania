test('Old public authors cannot silently become a new private recipient; private originals load outside the latest page',async t=>{
 const {db,rpc,token,send,freeRate,devices,bind}=await setup(t);
 const publicMessage=await rpc('send',[token[1],randomUUID(),'Старый автор']);
 assert.equal((await rpc('read',[token[2],null,null])).messages[0].canPrivate,true);
 const first=await send(token[1],2,'Первый оригинал');
 for(let i=0;i<42;i++)await send(token[1],2,'Строка '+i);
 const last=await send(token[2],1,'Ответ на первую строку',first.id);
 const latest=await rpc('private_read',[token[2],first.conversation,null,null]);
 assert.equal(latest.messages.length,40);assert.equal(latest.messages.some(x=>x.id===first.id),false);assert.equal(latest.hasOlder,true);
 assert.equal((await rpc('private_message',[token[2],first.conversation,first.id])).messages.some(x=>x.id===first.id),true);
 await assert.rejects(rpc('private_send',[token[2],1,(await rpc('private_list',[token[2]])).items.find(x=>x.room===1).peerPeriod,randomUUID(),'Без обхода частоты',null]),{code:'PT429'});
 const current=(await devices(token[1])).find(d=>d.current);const oldGeneration=(await db.query('select generation from g19_private.rooms where room=1')).rows[0].generation;
 await rpc('revoke_device',[token[1],current.id]);await bind(1);
 assert.equal((await db.query('select generation from g19_private.rooms where room=1')).rows[0].generation,oldGeneration);
 assert.equal((await rpc('read',[token[2],null,null])).messages.find(x=>x.id===publicMessage).canPrivate,false);
 assert.equal((await rpc('private_read',[token[2],first.conversation,null,null])).readOnly,true);
 assert.ok(last.id);await freeRate();
});
